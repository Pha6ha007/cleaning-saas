"""
Bilingual Arabic/English Maintenance Visit PDF Report (M004/S01)

Generates a standalone PDF using fpdf2 (NOT ReportLab) with:
- Arabic and English labels side-by-side
- Correct RTL Arabic text via arabic_reshaper + bidi algorithm
- Bundled Amiri font for Arabic glyphs
- Falls back to English-only if Arabic font is unavailable

Architecture:
- generate_bilingual_visit_report_pdf(job): main entry point → bytes
- _reshape_arabic(text): arabic_reshaper + bidi → display-ready string
- _find_arabic_font(): locates bundled Amiri .ttf for fpdf2
- BilingualVisitReport(FPDF): page layout, header, sections

Usage:
    from apps.api.bilingual_pdf import generate_bilingual_visit_report_pdf
    pdf_bytes = generate_bilingual_visit_report_pdf(job)

Dependencies:
    fpdf2==2.8.3
    arabic-reshaper==3.0.0
    python-bidi==0.4.2
    Amiri-Regular.ttf  (bundled in apps/api/fonts/)
"""

import logging
import os
from typing import Optional

logger = logging.getLogger(__name__)

# Path to bundled Amiri font directory
_FONTS_DIR = os.path.join(os.path.dirname(__file__), "fonts")


def _find_arabic_font() -> Optional[str]:
    """
    Find Amiri-Regular.ttf in bundled fonts dir.
    Returns absolute path or None if not found.
    """
    candidates = [
        os.path.join(_FONTS_DIR, "Amiri-Regular.ttf"),
        os.path.join(_FONTS_DIR, "Amiri-Bold.ttf"),
    ]
    for path in candidates:
        if os.path.exists(path):
            return path
    logger.warning("Arabic font not found in %s — bilingual PDF will use English only", _FONTS_DIR)
    return None


def _reshape_arabic(text: str) -> str:
    """
    Apply arabic_reshaper + python-bidi to produce display-ready Arabic string.
    Required for correct glyph joining and RTL visual order in PDFs.
    Returns the original text unchanged on any error.
    """
    if not text:
        return text
    try:
        import arabic_reshaper
        from bidi.algorithm import get_display
        reshaped = arabic_reshaper.reshape(text)
        return get_display(reshaped)
    except Exception as exc:
        logger.warning("Arabic reshaping failed: %s", exc)
        return text


